"""Generates SingleByteTables.swift for ChitallCore from Python's codecs.

Usage: python -I tools/gen_encoding_tables.py > ChitallCore/Sources/ChitallCore/FB2/SingleByteTables.swift

Each table maps bytes 0x80...0xFF to Unicode scalars. Undefined bytes map to U+FFFD.
"""

import sys

ENCODINGS = [
    ("windows1251", "cp1251"),
    ("koi8r", "koi8_r"),
    ("cp866", "cp866"),
    ("windows1252", "cp1252"),
]


def table(codec: str) -> list[int]:
    result = []
    for byte in range(0x80, 0x100):
        try:
            result.append(ord(bytes([byte]).decode(codec)))
        except UnicodeDecodeError:
            result.append(0xFFFD)
    return result


def main() -> None:
    out = sys.stdout
    out.write("// Generated by tools/gen_encoding_tables.py from Python codecs. Do not edit by hand.\n")
    out.write("// Each table maps bytes 0x80...0xFF to Unicode scalar values; 0xFFFD marks undefined bytes.\n\n")
    out.write("enum SingleByteTables {\n")
    for name, codec in ENCODINGS:
        values = table(codec)
        out.write(f"    static let {name}: [UInt32] = [\n")
        for row in range(0, 128, 8):
            chunk = ", ".join(f"0x{v:04X}" for v in values[row:row + 8])
            out.write(f"        {chunk},\n")
        out.write("    ]\n\n")
    out.write("}\n")


if __name__ == "__main__":
    main()
