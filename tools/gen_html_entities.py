"""Generates the table of HTML 4 named character entities for EPUB 2 XHTML.

Usage: python -I tools/gen_html_entities.py

XHTML 1.1 documents in EPUB 2 use entities such as &nbsp; or &mdash; that are declared only
in the external DTD, which Chitall never loads (offline, no external entities). The parser
replaces them with numeric references before XMLParser sees the text. The names come from
Python's html.entities.name2codepoint, which is exactly the HTML 4.01 / XHTML 1.x set.
"""

import html.entities
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ROOT / "ChitallCore" / "Sources" / "ChitallCore" / "EPUB" / "HTMLEntities.swift"
XML_PREDEFINED = {"amp", "lt", "gt", "quot", "apos"}


def main() -> None:
    names = sorted(n for n in html.entities.name2codepoint if n not in XML_PREDEFINED)
    lines = [
        "// Generated by tools/gen_html_entities.py from Python's html.entities. Do not edit.",
        "",
        "/// HTML 4 / XHTML 1.x named entities (without the five XML ones) → Unicode code point.",
        "enum HTMLEntities {",
        "    static let codePoints: [String: UInt32] = [",
    ]
    for name in names:
        lines.append(f'        "{name}": 0x{html.entities.name2codepoint[name]:04X},')
    lines += ["    ]", "}", ""]
    TARGET.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(TARGET.name, len(names), "entities")


if __name__ == "__main__":
    main()
